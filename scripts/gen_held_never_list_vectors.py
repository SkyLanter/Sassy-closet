#!/usr/bin/env python3
"""Generate scripts/testdata/held-never-list-vectors.json from data/held.json (the one source).

mã codes only. Writes only the vector file; --check exits 1 if the committed vector is stale.
Controls are never-held mãs used to prove a non-held mã is not reported held.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HELD = ROOT / "data" / "held.json"
OUT = ROOT / "scripts" / "testdata" / "held-never-list-vectors.json"
CONTROLS = ("S06", "A01", "K01", "Q01")  # S06 = $25 lock; must not be held unless data/held.json says so


def variants(ma: str) -> list[str]:
    letter, n = ma[0], int(ma[1:])
    out = [f"{letter}{n:03d}", f" {ma.lower()} ", ma.lower(), f"\t{ma}\n"]
    if n < 10:
        out.append(f"{letter.lower()}{n}")
    return out


def build(held_path: Path = HELD) -> dict:
    src = json.loads(held_path.read_text(encoding="utf-8"))
    held, never = list(src["heldIncomplete"]), list(src["neverList"])
    rows = []
    for status, codes in (("held", held), ("never-list", never)):
        for ma in codes:
            rows.append({"ma": ma, "status": status, "variants": variants(ma)})
    for ma in CONTROLS:
        if ma not in held and ma not in never:
            rows.append({"ma": ma, "status": "none", "variants": variants(ma)})
    return {
        "about": "Generated by scripts/gen_held_never_list_vectors.py from data/held.json. mã codes only. "
                 "Every variant must get the same verdict as its canonical mã in Python, shop and intake.",
        "source": "data/held.json",
        "heldIncomplete": held,
        "neverList": never,
        "s06LockUsd": 25,
        "rows": rows,
    }


def render(d: dict) -> str:
    return json.dumps(d, ensure_ascii=False, indent=1) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed vector is stale")
    a = ap.parse_args(argv)
    text = render(build())
    if a.check:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("held-never-list vector: " + ("up to date" if ok else "STALE, rerun the generator"))
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
